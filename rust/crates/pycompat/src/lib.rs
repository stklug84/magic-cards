//! CPython-compatible building blocks for byte-exact output parity.
//!
//! The Python simulator's observable output (seeded shuffles, the
//! `--log-file` and `--viz-file` JSONL records, the statistics report)
//! is defined by CPython behaviour: `random.Random(seed)` with
//! `shuffle`/`randrange`, `json.dumps` with its default separators and
//! float repr, `str.format` specs such as `{:5.1f}`, and the exact
//! rational arithmetic of `statistics.stdev`. This crate reproduces those
//! pieces so that the Rust simulator produces the same bytes for the same
//! seed:
//!
//! - [`random::PyRandom`]: MT19937 with CPython's seeding and methods;
//! - [`json`]: an insertion-ordered [`json::Value`] and [`json::dumps`];
//! - [`pyfloat`]: `repr`, `%f` and `%g` of floats;
//! - [`pyfmt`]: the format-spec mini-language subset the reports use;
//! - [`stats`]: `statistics.mean`, `median` and `stdev`, exactly;
//! - [`pyrepr`]: `repr` of the payloads the viz layer prints verbatim.
//!
//! Every module is verified against vectors generated by CPython
//! (`scripts/parity/vectors.py`, committed under `tests/vectors/`;
//! regenerate with `cargo xtask vectors`).

pub mod json;
pub mod pyfloat;
pub mod pyfmt;
pub mod pyrepr;
pub mod random;
pub mod stats;
