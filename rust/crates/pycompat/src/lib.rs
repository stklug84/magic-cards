//! CPython-compatible building blocks for byte-exact output.
//!
//! The simulator's observable output (seeded shuffles, the `--log-file`
//! and `--viz-file` JSONL records, the statistics report) was defined by
//! the Python implementation it replaced, i.e. by CPython behaviour:
//! `random.Random(seed)` with `shuffle`/`randrange`, `json.dumps` with
//! its default separators and float repr, `str.format` specs such as
//! `{:5.1f}`, and the exact rational arithmetic of `statistics.stdev`.
//! This crate reproduces those pieces, so a seed still produces the bytes
//! it always did - recordings and logs made before the cutover replay
//! unchanged:
//!
//! - [`random::PyRandom`]: MT19937 with CPython's seeding and methods;
//! - [`json`]: an insertion-ordered [`json::Value`] and [`json::dumps`];
//! - [`pyfloat`]: `repr`, `%f` and `%g` of floats;
//! - [`pyfmt`]: the format-spec mini-language subset the reports use;
//! - [`stats`]: `statistics.mean`, `median` and `stdev`, exactly;
//! - [`pyrepr`]: `repr` of the payloads the viz layer prints verbatim;
//! - [`pystr`], [`pyio`], [`pypath`], [`pyurl`]: `str.splitlines`,
//!   `int()`, `Path.read_text` with universal newlines and Python's error
//!   text, `str(Path)` normalisation and `urllib.parse.quote` — the
//!   `str`-level semantics the data layer's readers depend on.
//!
//! Every module is verified against vectors generated by CPython 3.12
//! before the Python implementation was retired (`tests/vectors/*.json`,
//! frozen goldens; the generator, `scripts/parity/vectors.py`, lives in
//! the git history up to the cutover).

pub mod json;
pub mod pyfloat;
pub mod pyfmt;
pub mod pyio;
pub mod pypath;
pub mod pyrepr;
pub mod pystr;
pub mod pyurl;
pub mod random;
pub mod stats;
